    #[test]
    fn test_batch_matches_single() {
        // Create a small 2x2x2 tricubic grid with a known linear field.
        // The tricubic field should interpolate correctly.
        let nx = 2;
        let ny = 2;
        let nz = 2;
        let mut data = vec![0.0f64; 8 * nx * ny * nz];
        let nynz = ny * nz;
        let nz_ = nz;

        // Fill with a linear field: f(sx,sy,sz) = 2*sx + 3*sy + 5*sz + 7
        for c in 0..8 {
            for i in 0..nx {
                for j in 0..ny {
                    for k in 0..nz {
                        let sx = i as f64 / (nx - 1) as f64;
                        let sy = j as f64 / (ny - 1) as f64;
                        let sz = k as f64 / (nz - 1) as f64;
                        let val = match c {
                            0 => 2.0 * sx + 3.0 * sy + 5.0 * sz + 7.0,
                            1 => 2.0, // fx
                            2 => 3.0, // fy
                            3 => 5.0, // fz
                            _ => 0.0,
                        };
                        data[c * nx * nynz + i * nynz + j * nz_ + k] = val;
                    }
                }
            }
        }

        let field = TricubicField {
            data,
            nx,
            ny,
            nz,
            extent_x: 1.0,
            extent_y: 1.0,
            extent_z: 1.0,
        };

        // Test a few points
        for (fx, fy, fz) in &[
            (0.25, 0.5, 0.75),
            (0.0, 0.0, 0.0),
            (0.5, 0.5, 0.5),
            (0.999, 0.001, 0.5),
        ] {
            let expected = 2.0 * fx + 3.0 * fy + 5.0 * fz + 7.0;
            let v = field._interpolate_impl([*fx, *fy, *fz]);
            assert!(
                (v - expected).abs() < 1e-10,
                "f({}, {}, {}) = {}, expected {}",
                fx,
                fy,
                fz,
                v,
                expected
            );
        }
    }

