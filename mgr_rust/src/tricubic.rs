//! Lekien–Marsden tricubic interpolation — Phase 1: evaluator.
//!
//! Implements the tricubic interpolation scheme from:
//!   F. Lekien and J. Marsden, "Tricubic interpolation in three dimensions",
//!   _Int. J. Numer. Meth. Engng_ 2005; 63:455–471.
//!
//! Reference implementation: RASPA3 (Dubbeldam et al.),
//!   `src/raspakit/interpolation_energy_grid.cpp`.
//!
//! # Data layout (RASPA-compatible)
//!
//! **X-ordering:** `X[channel * 8 + corner]` where:
//! - `corner = cx + 2·cy + 4·cz`  for `cx, cy, cz ∈ {0, 1}`
//! - channel 0 = _f_, 1 = ∂_f_/∂_x_, 2 = ∂_f_/∂_y_, 3 = ∂_f_/∂_z_
//! - channel 4 = ∂²_f_/∂_x_∂_y_, 5 = ∂²_f_/∂_x_∂_z_, 6 = ∂²_f_/∂_y_∂_z_, 7 = ∂³_f_/∂_x_∂_y_∂_z_
//!
//! **Coefficient ordering:** `a[i + 4·j + 16·k]` for `i, j, k ∈ {0, 1, 2, 3}`.
//!
//! **Interpolation formula:**
//! `f(sx, sy, sz) = Σ_{i,j,k=0..3} a[i+4j+16k] · sxⁱ · syʲ · szᵏ`
//!
//! The 64×64 matrix _M_ maps data → coefficients (`a = M·X`). It is the inverse of the
//! Vandermonde constraint matrix that encodes the 8 conditions per corner.
//! The matrix was derived independently from the Lekien–Marsden constraints and
//! verified against the RASPA3 reference — no GPL code was copied.


