/// Compute the interpolated value for a single cell given its 64 data values.
///
/// `x` is `[f64; 64]` indexed as `X[channel * 8 + corner]`.
/// `sx, sy, sz` are the local coordinates within the cell, each in `[0, 1]`.
#[pyfunction]
#[pyo3(text_signature = "(x, sx, sy, sz)")]
fn tricubic_interpolate_cell(x: Vec<f64>, sx: f64, sy: f64, sz: f64) -> PyResult<f64> {
    if x.len() != 64 {
        return Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(format!(
            "x must have length 64, got {}",
            x.len()
        )));
    }
    let mut x_arr = [0.0f64; 64];
    x_arr.copy_from_slice(&x);
    let a = compute_coefficients(&x_arr);
    Ok(interpolate_energy(&a, sx, sy, sz))
}

