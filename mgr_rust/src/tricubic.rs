/// Compute the 64 polynomial coefficients `a` from the 64 data values `X`.
///
/// `X` is indexed as `X[channel * 8 + corner]` (see module docs).
/// Returns `a[64]` with `a[i + 4*j + 16*k]` for `i, j, k ∈ {0, 1, 2, 3}`.
#[inline]
pub fn compute_coefficients(x: &[f64; 64]) -> [f64; 64] {
    let mut a = [0.0f64; 64];
    for i in 0..64 {
        let row = &TRICUBIC_COEFFICIENTS[i];
        let mut sum = 0.0;
        // No branch on zero: multiplying by 0.0 is free in SIMD FMAs;
        // the branch was blocking auto-vectorization (reviewer P1).
        for j in 0..64 {
            sum += row[j] * x[j];
        }
        a[i] = sum;
    }
    a
}

/// Evaluate the tricubic polynomial at local coordinates `(sx, sy, sz) ∈ [0,1]³`.
#[inline]
pub fn interpolate_energy(a: &[f64; 64], sx: f64, sy: f64, sz: f64) -> f64 {
    let sx2 = sx * sx;
    let sx3 = sx2 * sx;
    let sy2 = sy * sy;
    let sy3 = sy2 * sy;
    let sz2 = sz * sz;
    let sz3 = sz2 * sz;

    let sx_pow = [1.0f64, sx, sx2, sx3];
    let sy_pow = [1.0f64, sy, sy2, sy3];
    let sz_pow = [1.0f64, sz, sz2, sz3];

    let mut value = 0.0;
    let mut idx = 0usize;
    for k in 0..4 {
        let szp = sz_pow[k];
        for j in 0..4 {
            let syzp = sy_pow[j] * szp;
            for i in 0..4 {
                value += a[idx] * sx_pow[i] * syzp;
                idx += 1;
            }
        }
    }
    value
}

/// Gather 64 values from an 8-channel grid at a specific cubic cell.
///
/// `data` is a flat `f64` slice of shape `(8, nx, ny, nz)` in C order
/// (last index varies fastest). The cell is defined by corners
/// `(x0, y0, z0)` and `(x1, y1, z1) = (x0+1, y0+1, z0+1)`.
#[inline]
pub fn gather_cell(
    data: &[f64],
    nx: usize,
    ny: usize,
    nz: usize,
    x0: usize,
    y0: usize,
    z0: usize,
    x1: usize,
    y1: usize,
    z1: usize,
    x: &mut [f64; 64],
) {
    let nynz = ny * nz;
    let nz_ = nz;

    for channel in 0..8 {
        let base = channel * nx * nynz;
        let off = channel * 8;
        x[off] = data[base + x0 * nynz + y0 * nz_ + z0];
        x[off + 1] = data[base + x1 * nynz + y0 * nz_ + z0];
        x[off + 2] = data[base + x0 * nynz + y1 * nz_ + z0];
        x[off + 3] = data[base + x1 * nynz + y1 * nz_ + z0];
        x[off + 4] = data[base + x0 * nynz + y0 * nz_ + z1];
        x[off + 5] = data[base + x1 * nynz + y0 * nz_ + z1];
        x[off + 6] = data[base + x0 * nynz + y1 * nz_ + z1];
        x[off + 7] = data[base + x1 * nynz + y1 * nz_ + z1];
    }
}

// ── PyO3: TricubicField ─────────────────────────────────────────────────────

/// Holds an 8-channel tricubic interpolation grid and evaluates it
/// at arbitrary fractional coordinates within the unit cell.
///
/// Constructed from a numpy array of shape `(8, nx, ny, nz)` in C order.
#[pyclass(name = "TricubicField")]
#[derive(Clone)]
pub struct TricubicField {
    /// Flat data: shape (8, nx, ny, nz) in C order (last index varies fastest).
    data: Vec<f64>,
    nx: usize,
    ny: usize,
    nz: usize,
    /// ASE fractional span per axis covered by the grid (1.0 = full cell).
    extent_x: f64,
    extent_y: f64,
    extent_z: f64,
}

#[pymethods]
impl TricubicField {
    /// Create a new `TricubicField` from an 8-channel energy grid.
    ///
    /// `data` must be a numpy `f64` array of shape `(8, nx, ny, nz)`
    /// in C-contiguous order.
    #[new]
    #[pyo3(signature = (data, extent_x=1.0, extent_y=1.0, extent_z=1.0))]
    fn new(
        data: PyReadonlyArrayDyn<'_, f64>,
        extent_x: f64,
        extent_y: f64,
        extent_z: f64,
    ) -> PyResult<Self> {
        let arr = data.as_array();
        let shape = arr.shape();
        if arr.ndim() != 4 || shape[0] != 8 {
            return Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(format!(
                "TricubicField expects 4-D array (8, nx, ny, nz), got shape {:?}",
                shape
            )));
        }
        let nx = shape[1];
        let ny = shape[2];
        let nz = shape[3];

        // Attempt fast zero-copy if contiguous; otherwise copy elementwise.
        let data_vec = if let Some(slice) = arr.as_slice() {
            slice.to_vec()
        } else {
            let nynz = ny * nz;
            let nz_ = nz;
            let mut v = vec![0.0f64; 8 * nx * nynz];
            for c in 0..8 {
                for i in 0..nx {
                    for j in 0..ny {
                        for k in 0..nz {
                            v[c * nx * nynz + i * nynz + j * nz_ + k] = arr[[c, i, j, k]];
                        }
                    }
                }
            }
            v
        };

        Ok(TricubicField {
            data: data_vec,
            nx,
            ny,
            nz,
            extent_x,
            extent_y,
            extent_z,
        })
    }

    /// Interpolate the energy at one fractional position.
    ///
    /// `frac` is `[fx, fy, fz]` in ASE unit-cell fractional coordinates
    /// (same convention as ``get_fractional_coordinates``). Values are wrapped
    /// into the first periodic tile when ``extent_* < 1`` before interpolation.
    fn interpolate(&self, frac: Vec<f64>) -> PyResult<f64> {
        if frac.len() != 3 {
            return Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(
                "frac must have length 3",
            ));
        }
        Ok(self._interpolate_impl([frac[0], frac[1], frac[2]]))
    }

    /// Interpolate energy at many fractional positions.
    ///
    /// `fracs` is a numpy `(N, 3)` array. Returns a numpy `(N,)` array of
    /// interpolated energies.
    fn interpolate_batch(
        &self,
        py: Python<'_>,
        fracs: PyReadonlyArray2<'_, f64>,
    ) -> PyResult<Py<PyArray1<f64>>> {
        let fracs = fracs.as_array();
        let n = fracs.shape()[0];
        if fracs.shape()[1] != 3 {
            return Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(format!(
                "fracs must have shape (N, 3), got {:?}",
                fracs.shape()
            )));
        }
        let mut result = Vec::with_capacity(n);
        for i in 0..n {
            result.push(self._interpolate_impl([
                fracs[[i, 0]],
                fracs[[i, 1]],
                fracs[[i, 2]],
            ]));
        }
        Ok(PyArray1::from_vec(py, result).to_owned())
    }

    /// Grid shape `(nx, ny, nz)`.
    #[getter]
    fn shape(&self) -> (usize, usize, usize) {
        (self.nx, self.ny, self.nz)
    }
}

impl TricubicField {
    /// Map ASE fractional coordinate to interpolator query coord in `[0, 1)`.
    ///
    /// The grid always covers one full unit cell (nx_unit points distributed
    /// across the first unit-cell tile of the supercell).  The query coordinate
    /// maps directly: ``frac → frac`` (no extent folding).  Extent is handled
    /// at grid-build time and in the derivative scaling inside
    /// ``egrid_tricubic_from_atoms``.
    fn ase_frac_to_query(ase_frac: f64, _extent: f64) -> f64 {
        let mut f = ase_frac - ase_frac.floor();
        if f >= 1.0 {
            f = 0.0;
        }
        if f >= 1.0 {
            1.0f64 - f64::EPSILON
        } else {
            f
        }
    }

    /// Core interpolation: fold ASE frac, locate the cell, gather corner data,
    /// compute coefficients, evaluate.
    fn _interpolate_impl(&self, frac: [f64; 3]) -> f64 {
        let fx = Self::ase_frac_to_query(frac[0], self.extent_x);
        let fy = Self::ase_frac_to_query(frac[1], self.extent_y);
        let fz = Self::ase_frac_to_query(frac[2], self.extent_z);

        // Degenerate case: fewer than 2 grid points along any axis
        if self.nx < 2 || self.ny < 2 || self.nz < 2 {
            let nynz = self.ny * self.nz;
            let nz_ = self.nz;
            let i = ((fx * (self.nx.saturating_sub(1)) as f64).round() as usize).min(self.nx.saturating_sub(1));
            let j = ((fy * (self.ny.saturating_sub(1)) as f64).round() as usize).min(self.ny.saturating_sub(1));
            let k = ((fz * (self.nz.saturating_sub(1)) as f64).round() as usize).min(self.nz.saturating_sub(1));
            return self.data[i * nynz + j * nz_ + k]; // channel 0 only
        }

        // Cell indices and local coordinates (RASPA lines 4080-4095)
        let x0_float = fx * (self.nx - 1) as f64;
        let x0 = (x0_float.floor() as usize).min(self.nx - 2);
        let sx = x0_float - x0 as f64;

        let y0_float = fy * (self.ny - 1) as f64;
        let y0 = (y0_float.floor() as usize).min(self.ny - 2);
        let sy = y0_float - y0 as f64;

        let z0_float = fz * (self.nz - 1) as f64;
        let z0 = (z0_float.floor() as usize).min(self.nz - 2);
        let sz = z0_float - z0 as f64;

        let mut x = [0.0f64; 64];
        gather_cell(
            &self.data,
            self.nx,
            self.ny,
            self.nz,
            x0,
            y0,
            z0,
            x0 + 1,
            y0 + 1,
            z0 + 1,
            &mut x,
        );

        let a = compute_coefficients(&x);
        let val = interpolate_energy(&a, sx, sy, sz);

        // RASPA corner clamp: prevent polynomial overshoot beyond the
        // physically meaningful range of the surrounding 2×2×2 cell.
        let corner_min = x[0..8].iter().cloned().reduce(f64::min).unwrap();
        let corner_max = x[0..8].iter().cloned().reduce(f64::max).unwrap();
        val.clamp(corner_min, corner_max)
    }
}

